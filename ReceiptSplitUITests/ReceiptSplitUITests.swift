import XCTest

final class ReceiptSplitUITests: XCTestCase {
    var app: XCUIApplication!
    override func setUpWithError() throws {
        continueAfterFailure = false
        app = XCUIApplication(); app.launchArguments = ["--uitesting"]; app.launch()
    }
    func replace(_ field: XCUIElement, with value: String) {
        XCTAssertTrue(field.waitForExistence(timeout: 5))
        field.tap()
        // Select the current value using the same keyboard shortcut used in Simulator.
        field.typeKey("a", modifierFlags: .command)
        field.typeText(value)
        XCTAssertEqual(field.value as? String, value)
    }
    func createReceipt() {
        app.buttons["New receipt"].tap()
        replace(app.textFields["merchantField"], with: "Campus Cafe")
        replace(app.textFields["Printed totalField"], with: "220.00")
        replace(app.textFields["CGSTField"], with: "10.00")
        replace(app.textFields["SGSTField"], with: "10.00")
        app.buttons["saveReceipt"].tap()
        XCTAssertTrue(app.cells["receipt-Campus Cafe"].waitForExistence(timeout: 5))
        app.cells["receipt-Campus Cafe"].tap()
        XCTAssertTrue(app.cells["addItem"].waitForExistence(timeout: 5))
    }
    func addPerson(_ name: String, paid: String) {
        app.cells["addPerson"].tap()
        replace(app.textFields["personNameField"], with: name)
        replace(app.textFields["Amount paidField"], with: paid)
        app.buttons["savePerson"].tap()
        XCTAssertTrue(app.cells["person-" + name].waitForExistence(timeout: 5))
    }
    func addItem() {
        app.cells["addItem"].tap()
        replace(app.textFields["itemNameField"], with: "Lunch")
        replace(app.textFields["quantityField"], with: "2")
        replace(app.textFields["Unit priceField"], with: "100.00")
        app.buttons["saveItem"].tap()
        XCTAssertTrue(app.cells["item-Lunch"].waitForExistence(timeout: 5))
    }
    func testCreateUpdateReconcileSettleAndDelete() {
        createReceipt()
        app.cells["participantsLink"].tap()
        addPerson("Aryan", paid: "220.00"); addPerson("Aditya", paid: "0.00")
        app.navigationBars.buttons.element(boundBy: 0).tap()
        addItem()
        XCTAssertTrue(app.staticTexts["Matches printed total"].exists)
        app.cells["item-Lunch"].tap()
        replace(app.textFields["itemNameField"], with: "Lunch combo")
        app.buttons["saveItem"].tap()
        XCTAssertTrue(app.cells["item-Lunch combo"].waitForExistence(timeout: 5))
        app.cells["settlementLink"].tap()
        XCTAssertTrue(app.staticTexts["All numbers checked"].waitForExistence(timeout: 5))
        app.swipeUp()
        app.cells["confirmReview"].tap()
        XCTAssertTrue(app.cells["shareSettlement"].waitForExistence(timeout: 5))
        let attachment = XCTAttachment(screenshot: app.screenshot()); attachment.name = "Verified settlement"; attachment.lifetime = .keepAlways; add(attachment)
        app.navigationBars.buttons.element(boundBy: 0).tap()
        app.buttons["Edit"].tap()
        replace(app.textFields["merchantField"], with: "Campus Kitchen")
        app.buttons["saveReceipt"].tap()
        XCTAssertTrue(app.navigationBars["Campus Kitchen"].waitForExistence(timeout: 5))
        app.cells["participantsLink"].tap()
        app.cells["person-Aditya"].tap()
        replace(app.textFields["personNameField"], with: "Adi")
        app.buttons["savePerson"].tap()
        XCTAssertTrue(app.cells["person-Adi"].waitForExistence(timeout: 5))
        app.cells["person-Adi"].swipeLeft()
        app.buttons["Delete"].tap()
        app.alerts.buttons["Remove"].tap()
        XCTAssertFalse(app.cells["person-Adi"].exists)
        app.navigationBars.buttons.element(boundBy: 0).tap()
        app.cells["item-Lunch combo"].swipeLeft()
        app.buttons["Delete"].tap()
        app.alerts.buttons["Delete"].tap()
        XCTAssertFalse(app.cells["item-Lunch combo"].exists)
        app.navigationBars.buttons.element(boundBy: 0).tap()
        app.cells["receipt-Campus Kitchen"].swipeLeft()
        app.buttons["Delete"].tap()
        app.alerts.buttons["Delete"].tap()
        XCTAssertTrue(app.staticTexts["Your next split starts here"].waitForExistence(timeout: 5))
    }
    func testValidationAndCancelLeaveDataUntouched() {
        app.buttons["New receipt"].tap()
        XCTAssertFalse(app.buttons["saveReceipt"].isEnabled)
        replace(app.textFields["merchantField"], with: "Cancelled")
        app.buttons["Cancel"].tap()
        XCTAssertFalse(app.staticTexts["Cancelled"].exists)
        createReceipt()
        app.cells["addItem"].tap()
        replace(app.textFields["itemNameField"], with: "Invalid item")
        replace(app.textFields["quantityField"], with: "0")
        replace(app.textFields["Unit priceField"], with: "100")
        app.buttons["saveItem"].tap()
        XCTAssertTrue(app.alerts["Couldn’t complete that action"].waitForExistence(timeout: 5))
        app.alerts.buttons["OK"].tap(); app.buttons["Cancel"].tap()
        XCTAssertFalse(app.staticTexts["Invalid item"].exists)
        app.cells["settlementLink"].tap()
        XCTAssertTrue(app.staticTexts["Add at least one participant."].waitForExistence(timeout: 5))
        XCTAssertFalse(app.cells["shareSettlement"].exists)
    }
    func testWeightedAndCustomSplits() {
        createReceipt()
        app.cells["participantsLink"].tap()
        addPerson("Aryan", paid: "220.00"); addPerson("Aditya", paid: "0.00")
        app.navigationBars.buttons.element(boundBy: 0).tap()
        addItem()
        app.cells["item-Lunch"].tap()
        app.cells["splitMethod"].tap()
        app.sheets.buttons["Weighted"].tap()
        replace(app.textFields["share-Aryan"], with: "3")
        replace(app.textFields["share-Aditya"], with: "1")
        app.buttons["saveItem"].tap()
        app.cells["settlementLink"].tap()
        XCTAssertTrue(app.staticTexts["Aditya pays Aryan"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.staticTexts.matching(NSPredicate(format: "label CONTAINS '55.00'")).firstMatch.exists)
        app.navigationBars.buttons.element(boundBy: 0).tap()
        app.cells["item-Lunch"].tap()
        app.cells["splitMethod"].tap()
        app.sheets.buttons["Custom amounts"].tap()
        replace(app.textFields["share-Aryan"], with: "120.00")
        replace(app.textFields["share-Aditya"], with: "80.00")
        app.buttons["saveItem"].tap()
        app.cells["settlementLink"].tap()
        XCTAssertTrue(app.staticTexts["Aditya pays Aryan"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.staticTexts.matching(NSPredicate(format: "label CONTAINS '88.00'")).firstMatch.exists)
    }
    func testSampleReceiptReviewAndSettlement() {
        app.cells["sampleSplit"].tap()
        XCTAssertTrue(app.cells["item-Lunch"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.staticTexts["Matches printed total"].exists)
        app.cells["participantsLink"].tap()
        XCTAssertTrue(app.cells["person-Alex"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.cells["person-Sam"].exists)
        app.navigationBars.buttons.element(boundBy: 0).tap()
        app.cells["item-Lunch"].tap()
        app.cells["splitMethod"].tap()
        app.sheets.buttons["Weighted"].tap()
        replace(app.textFields["share-Alex"], with: "3")
        replace(app.textFields["share-Sam"], with: "1")
        app.buttons["saveItem"].tap()
        app.cells["settlementLink"].tap()
        XCTAssertTrue(app.staticTexts["All numbers checked"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.staticTexts["Sam pays Alex"].exists)
        app.swipeUp()
        app.cells["confirmReview"].tap()
        XCTAssertTrue(app.cells["shareSettlement"].waitForExistence(timeout: 5))
    }
}
